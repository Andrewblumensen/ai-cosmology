"""Score every model in the idea-factory catalogue and write a leaderboard.

Data: DESI DR2 BAO + compressed CMB + Pantheon+ (DES-SN5YR stays held out).
Columns: Delta chi2 and Delta AIC vs LCDM and vs w0wa (negative = better), min w over
0 <= z <= 3, and whether w crosses -1. Pre-registration: IDEAS.md, ID-035.

Usage: python scripts/run_catalogue.py   -> docs/catalogue-leaderboard.md
"""

import os

os.environ.setdefault("OMP_NUM_THREADS", "1")

import sys  # noqa: E402
from multiprocessing import Pool  # noqa: E402
from pathlib import Path  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from aicosmo.catalogue import CATALOGUE  # noqa: E402
from aicosmo.score import LCDM, W0WA, Data, score  # noqa: E402

DATA = Data(cmb=True, sn=True)
MODELS = [LCDM, W0WA] + CATALOGUE


def one(i: int):
    m = MODELS[i]
    s = score(m, DATA, errors=False, starts=1 if not m.params else 4)
    return i, s


def main() -> None:
    results = {}
    with Pool(min(16, os.cpu_count())) as pool:
        for i, s in pool.imap_unordered(one, range(len(MODELS))):
            results[i] = s
            print(f"  [{len(results)}/{len(MODELS)}] {s.model}: chi2 = {s.chi2:.2f}", flush=True)
    lcdm, w0wa = results[0], results[1]
    rows = sorted(results.values(), key=lambda s: s.aic)
    lines = [
        "# Idea-factory leaderboard",
        "",
        "Generated by `scripts/run_catalogue.py`. Data: DESI DR2 BAO + CMB (θ*, ω_b, ω_bc) + "
        "Pantheon+. Negative Δ = better than the reference. ΔAIC = Δχ² + 2 Δk.",
        "",
        "| Rank | Model | k | Δχ² vs ΛCDM | ΔAIC vs ΛCDM | ΔAIC vs w0wa | min w (z≤3) | crosses −1 | Best fit | Source |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r, s in enumerate(rows, 1):
        m = next(m for m in MODELS if m.name == s.model)
        best = ", ".join(f"{k}={s.best[k]:.3g}" for k in m.params)
        lines.append(f"| {r} | {s.model} | {s.k} | {s.chi2 - lcdm.chi2:+.2f} | {s.aic - lcdm.aic:+.2f} | "
                     f"{s.aic - w0wa.aic:+.2f} | {s.w_min:.2f} | {'yes' if s.phantom_crossing else 'no'} | "
                     f"{best} | {m.source} |")
    out = ROOT / "docs" / "catalogue-leaderboard.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
